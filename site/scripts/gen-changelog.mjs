// Bundle the repo's CHANGELOG.md into the site as a TS module so the on-site
// changelog page renders the SAME source of truth the package ships — no drift,
// no runtime fs read (which wouldn't be traced into the standalone build).
// Runs at predev/prebuild. Also extracts the latest released version heading.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, "../../CHANGELOG.md");
const DEST = join(here, "../lib/changelog.generated.ts");

if (!existsSync(SRC)) {
  console.warn("[site gen-changelog] no ../../CHANGELOG.md; skipping");
  process.exit(0);
}

const md = readFileSync(SRC, "utf8");
// Latest *released* version = first `## [x.y.z]` heading (skips [Unreleased]).
const m = md.match(/^##\s*\[(\d+\.\d+\.\d+)\]/m);
const latestVersion = m ? m[1] : "";

const out =
  `// GENERATED by scripts/gen-changelog.mjs from the repo CHANGELOG.md — do not edit.\n` +
  `export const CHANGELOG_MD = ${JSON.stringify(md)};\n` +
  `export const CHANGELOG_LATEST_VERSION = ${JSON.stringify(latestVersion)};\n`;

writeFileSync(DEST, out);
console.log(`[site gen-changelog] wrote lib/changelog.generated.ts (${md.length} chars, latest v${latestVersion})`);
