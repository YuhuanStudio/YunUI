"use client";

import { useCallback, useEffect, useLayoutEffect, useRef, useState, type ReactNode } from "react";
import { ArrowUp, Check, ChevronRight, CircleHelp, RefreshCw, Scissors, Sparkles, ThumbsUp, Type, X } from "lucide-react";
import { Button } from "../primitives";
import { cn } from "../lib/cn";
import { mergeLabels } from "../lib/merge-labels";

/** One host-owned action in the contextual selection bar. */
export interface SelectionAction {
  /** Stable host action identifier; callbacks receive `action ?? id`. */
  id: string;
  /** Optional localized visible label; defaults to the stable ID. */
  label?: ReactNode;
  icon?: ReactNode;
  /** Value reported to the host callback; defaults to `id`. */
  action?: string;
  /** Host-provided activity label for this action while the host reports busy. */
  busyLabel?: string;
}

export type SelectionActionsState = "idle" | "busy" | "result" | "error" | "cancelled";

export interface SelectionActionsLabels {
  keep?: string;
  discard?: string;
  placeholder?: string;
  submitInstruction?: string;
  customAction?: string;
  working?: string;
  error?: string;
  cancelled?: string;
  retry?: string;
  showMoreActions?: string;
  showFewerActions?: string;
  result?: string;
}

export interface SelectionActionsProps {
  /** Optional prose immediately before the selected passage. */
  lead?: ReactNode;
  selectedText: string;
  /** Host-provided rewrite. It is never generated by this component. */
  resultText?: string;
  /** Host owns all request state; no internal request timer or optimistic result. */
  state?: SelectionActionsState;
  /** Host-owned actions. Omitting this uses the general-purpose default action set. */
  actions?: readonly SelectionAction[];
  /** Current host activity label; used only while `state="busy"`. */
  busyLabel?: ReactNode;
  labels?: SelectionActionsLabels;
  disabled?: boolean;
  onAction?: (action: string, instruction?: string) => void;
  onAccept?: (result: string) => void;
  onDismiss?: () => void;
  onRetry?: () => void;
  className?: string;
}

const DEFAULT_LABELS: Required<SelectionActionsLabels> = {
  keep: "Keep",
  discard: "Discard",
  placeholder: "Describe edits",
  submitInstruction: "Submit custom instruction",
  customAction: "Custom instruction",
  working: "Working",
  error: "The edit request failed. Original text is unchanged.",
  cancelled: "Edit request cancelled. Original text is unchanged.",
  retry: "Try again",
  showMoreActions: "Show more actions",
  showFewerActions: "Show fewer actions",
  result: "Suggested edit",
};

const iconProps = { size: 14, strokeWidth: 1.8, "aria-hidden": true as const };
const DEFAULT_ACTIONS: readonly SelectionAction[] = [
  { id: "Explain", action: "Explain", icon: <CircleHelp {...iconProps} /> },
  { id: "Improve", action: "Improve", busyLabel: "Improving", icon: <Sparkles {...iconProps} /> },
  { id: "Shorten", action: "Shorten", busyLabel: "Shortening", icon: <Scissors {...iconProps} /> },
  { id: "Tone", action: "Change tone", busyLabel: "Changing tone", icon: <ThumbsUp {...iconProps} /> },
  { id: "Grammar", action: "Fix grammar", icon: <Type {...iconProps} /> },
];

const useIsomorphicLayoutEffect = typeof window === "undefined" ? useEffect : useLayoutEffect;

/**
 * Contextual actions anchored below host-selected text. The host supplies the
 * passage, generated result, request lifecycle, and callbacks. Adapted from the
 * pinned MIT source `reference/beautiful-ui/components/primitives/SelectionActions.tsx`
 * at `44a274e598395ab61e7c96c26fda2758780253b7`.
 */
export function SelectionActions({
  lead = "",
  selectedText,
  resultText,
  state = "idle",
  actions = DEFAULT_ACTIONS,
  busyLabel,
  labels,
  disabled = false,
  onAction,
  onAccept,
  onDismiss,
  onRetry,
  className,
}: SelectionActionsProps) {
  const copy = mergeLabels(DEFAULT_LABELS, labels);
  const [prompt, setPrompt] = useState("");
  const [expanded, setExpanded] = useState(false);
  const [anchor, setAnchor] = useState({ x: 0, y: 0 });
  const [positioned, setPositioned] = useState(false);
  const [maxBarWidth, setMaxBarWidth] = useState(0);
  const hostRef = useRef<HTMLDivElement>(null);
  const selectionRef = useRef<HTMLSpanElement>(null);
  const barRef = useRef<HTMLDivElement>(null);
  const frameRef = useRef<{ id: number; kind: "raf" | "timeout" } | null>(null);
  const previousSelectionRef = useRef(selectedText);

  const place = useCallback(() => {
    if (typeof window === "undefined") return;
    if (frameRef.current) {
      if (frameRef.current.kind === "raf") window.cancelAnimationFrame(frameRef.current.id);
      else window.clearTimeout(frameRef.current.id);
    }
    const measure = () => {
      frameRef.current = null;
      const host = hostRef.current;
      const selected = selectionRef.current;
      if (!host || !selected) return;
      const bounds = selected.getBoundingClientRect();
      const lines = Array.from(selected.getClientRects());
      const lastLine = lines.at(-1);
      const hostBounds = host.getBoundingClientRect();
      if (!lastLine || bounds.width === 0 || bounds.height === 0 || hostBounds.width === 0) {
        setPositioned(false);
        return;
      }
      const availableWidth = Math.max(0, Math.min(hostBounds.width - 16, window.innerWidth - 48));
      setMaxBarWidth((current) => Math.abs(current - availableWidth) < 1 ? current : availableWidth);
      const barWidth = barRef.current?.getBoundingClientRect().width ?? 0;
      const hostPadding = Math.min(8, hostBounds.width / 2);
      const halfBar = Math.min(barWidth / 2, Math.max(0, hostBounds.width / 2 - hostPadding));
      const minX = hostPadding + halfBar;
      const maxX = Math.max(minX, hostBounds.width - hostPadding - halfBar);
      const next = {
        x: Math.round(Math.min(maxX, Math.max(minX, bounds.left - hostBounds.left + bounds.width / 2))),
        y: Math.round(lastLine.bottom - hostBounds.top + 8),
      };
      setAnchor((current) => current.x === next.x && current.y === next.y ? current : next);
      setPositioned(true);
    };
    frameRef.current = typeof window.requestAnimationFrame === "function"
      ? { id: window.requestAnimationFrame(measure), kind: "raf" }
      : { id: window.setTimeout(measure, 0), kind: "timeout" };
  }, []);

  useIsomorphicLayoutEffect(() => {
    if (previousSelectionRef.current !== selectedText) {
      previousSelectionRef.current = selectedText;
      setPrompt("");
      setExpanded(false);
    }
    place();
  }, [place, selectedText, resultText, state, lead]);

  useEffect(() => {
    const host = hostRef.current;
    const selected = selectionRef.current;
    if (!host) return;
    const resizeObserver = typeof ResizeObserver !== "undefined"
      ? new ResizeObserver(() => place())
      : null;
    if (resizeObserver) {
      resizeObserver.observe(host);
      if (selected) resizeObserver.observe(selected);
      if (barRef.current) resizeObserver.observe(barRef.current);
    }
    // ResizeObserver is optional: text/host prop changes also call `place`, and
    // window resize remains the fallback for hosts without observer support.
    window.addEventListener("resize", place);
    return () => {
      resizeObserver?.disconnect();
      window.removeEventListener("resize", place);
      if (frameRef.current) {
        if (frameRef.current.kind === "raf") window.cancelAnimationFrame(frameRef.current.id);
        else window.clearTimeout(frameRef.current.id);
        frameRef.current = null;
      }
    };
  }, [place]);

  const busy = state === "busy";
  const hasResult = state === "result" && typeof resultText === "string";
  const locked = busy || disabled;
  const visibleText = hasResult ? resultText! : selectedText;
  const activity = busyLabel ?? labels?.working ?? DEFAULT_LABELS.working;

  const run = (action: string, instruction?: string) => {
    if (locked || !onAction) return;
    setExpanded(false);
    onAction(action, instruction);
  };

  const submitPrompt = (event: React.FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const instruction = prompt.trim();
    if (!instruction) return;
    run(labels?.customAction ?? DEFAULT_LABELS.customAction, instruction);
  };

  return (
    <div className={cn("@container/selection w-full max-w-[460px]", className)} data-yunui="selection-actions" data-selection-state={state}>
      <div ref={hostRef} data-yunui="selection-actions-host" className="relative pb-12">
        <p className="text-[13px] leading-relaxed text-foreground">
          {lead}
          <span ref={selectionRef} data-yunui="selection-actions-selected" style={hasResult && resultText === "" ? { display: "inline-block", minWidth: 1, minHeight: "1em" } : undefined} className="box-decoration-clone rounded-[3px] bg-accent-subtle text-foreground">
            {hasResult ? <span className="sr-only">{copy.result}: </span> : null}
            {visibleText}
          </span>
        </p>

        <div
          data-yunui="selection-actions-anchor"
          className="absolute left-0 top-0 z-10"
          style={{
            transform: `translate3d(${anchor.x}px, ${anchor.y}px, 0) translateX(-50%)`,
            transition: "transform 320ms cubic-bezier(0.77,0,0.175,1), opacity 180ms ease-out",
            opacity: positioned ? 1 : 0,
            pointerEvents: positioned ? "auto" : "none",
            willChange: "transform",
          }}
          aria-hidden={!positioned}
          inert={!positioned}
        >
          <div
            ref={barRef}
            className={cn(
              "flex w-fit max-w-[calc(100vw-48px)] items-center justify-center gap-0.5 rounded-full border border-border bg-card p-1 font-sans text-foreground shadow-lg",
              state === "error" || state === "cancelled" || busy ? "min-h-9" : "h-9 overflow-hidden",
            )}
            style={maxBarWidth > 0 ? { maxWidth: maxBarWidth } : undefined}
          >
            {busy ? (
              <span role="status" className="inline-flex min-w-0 max-w-full items-center gap-1.5 whitespace-normal break-words px-2.5 py-1 text-[12.5px] text-[var(--text-secondary)]">
                <span aria-hidden="true" className="size-3 shrink-0 rounded-full border-[1.5px] border-border border-t-foreground motion-safe:animate-spin" />
                {activity}…
              </span>
            ) : null}

            {hasResult ? (
              <>
                <Button type="button" variant="primary" size="sm" className="h-7 shrink-0 rounded-full px-2.5 text-[12.5px]" disabled={disabled || !onAccept} onClick={() => { if (resultText !== undefined) onAccept?.(resultText); }}>
                  <Check aria-hidden="true" size={14} />{copy.keep}
                </Button>
                {onDismiss ? <Button type="button" variant="ghost" size="sm" className="h-7 shrink-0 rounded-full px-2.5 text-[12.5px]" disabled={disabled} onClick={onDismiss}><X aria-hidden="true" size={14} />{copy.discard}</Button> : null}
                <span aria-hidden="true" className="mx-0.5 h-4 w-px shrink-0 bg-border" />
                {onRetry ? <Button type="button" variant="ghost" size="icon" className="size-7 shrink-0 rounded-full p-0" disabled={disabled} aria-label={copy.retry} onClick={onRetry}><RefreshCw aria-hidden="true" size={14} /></Button> : null}
              </>
            ) : null}

            {state === "error" || state === "cancelled" ? (
              <>
                <span role="status" className="min-w-0 max-w-[min(18rem,calc(100vw-8rem))] whitespace-normal break-words px-2 py-1 text-[11px] leading-snug text-[var(--text-secondary)]">{state === "error" ? labels?.error ?? DEFAULT_LABELS.error : labels?.cancelled ?? DEFAULT_LABELS.cancelled}</span>
                {onDismiss ? <Button type="button" variant="ghost" size="sm" className="h-7 shrink-0 rounded-full px-2.5 text-[12.5px]" disabled={disabled} onClick={onDismiss}>{copy.discard}</Button> : null}
                {onRetry ? <Button type="button" variant="ghost" size="icon" className="size-7 shrink-0 rounded-full p-0" disabled={disabled} aria-label={copy.retry} onClick={onRetry}><RefreshCw aria-hidden="true" size={14} /></Button> : null}
              </>
            ) : null}

            {state === "idle" ? (
              <>
                <div
                  className="flex min-w-0 items-center overflow-hidden transition-[max-width,opacity,transform] duration-300"
                  aria-hidden={expanded}
                  inert={expanded}
                  style={{ maxWidth: expanded ? 0 : 145, opacity: expanded ? 0 : 1, transform: expanded ? "translateX(-8px)" : "translateX(0)", transitionTimingFunction: "cubic-bezier(0.23,1,0.32,1)" }}
                >
                  <form className="flex h-7 w-[145px] min-w-0 shrink-0 items-center max-[420px]:w-[94px] @max-[360px]/selection:w-[94px]" onSubmit={submitPrompt}>
                    <input
                      value={prompt}
                      onChange={(event) => setPrompt(event.target.value)}
                      aria-label={copy.placeholder}
                      placeholder={copy.placeholder}
                      disabled={disabled || !onAction}
                      className="h-7 w-full min-w-0 bg-transparent py-0 pr-2.5 pl-3 text-[12.5px] text-foreground placeholder:text-muted-foreground focus:outline-none max-[420px]:pr-0 max-[420px]:pl-2 @max-[360px]/selection:pr-0 @max-[360px]/selection:pl-2"
                    />
                    <button type="submit" aria-label={copy.submitInstruction} disabled={disabled || !onAction || !prompt.trim()} className="mr-1 flex size-6 shrink-0 items-center justify-center rounded-full text-foreground hover:bg-muted disabled:opacity-40">
                      <ArrowUp aria-hidden="true" size={13} />
                    </button>
                  </form>
                </div>

                <span aria-hidden="true" className="mx-1 h-4 w-px shrink-0 bg-border" />
                <div
                  data-yunui="selection-actions-scroll"
                  className="flex min-w-0 flex-1 items-center gap-0.5 overflow-x-auto overflow-y-hidden overscroll-x-contain [scrollbar-width:none]"
                >
                  {(expanded ? actions : actions.slice(0, 2)).map(item => (
                    <Button
                      key={item.id}
                      type="button"
                      variant="ghost"
                      size="sm"
                      className="h-7 shrink-0 rounded-full px-2.5 text-[12px]"
                      disabled={disabled || !onAction}
                      onClick={() => run(item.action ?? item.id)}
                    >
                      {item.icon}{item.label ?? item.id}
                    </Button>
                  ))}
                </div>
                {actions.length > 2 ? (
                  <>
                    <span aria-hidden="true" className="mx-0.5 h-4 w-px shrink-0 bg-border" />
                    <button
                      type="button"
                      aria-label={expanded ? copy.showFewerActions : copy.showMoreActions}
                      aria-expanded={expanded}
                      disabled={disabled}
                      onClick={() => setExpanded(value => !value)}
                      className="flex size-7 shrink-0 items-center justify-center rounded-full text-foreground transition-[background-color,transform] hover:bg-muted active:scale-[0.96] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
                    >
                      <ChevronRight aria-hidden="true" size={14} style={{ transform: expanded ? "rotate(180deg)" : undefined }} />
                    </button>
                  </>
                ) : null}
              </>
            ) : null}
          </div>
        </div>
      </div>
    </div>
  );
}

export default SelectionActions;
